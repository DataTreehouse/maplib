const GRAPH_COL: &str = "graph";

#[derive(Debug, Clone)]
pub struct R2RMLOptions {
    /// The base IRI that relative IRIs generated by the mapping are resolved against.
    pub base_iri: String,
    /// The graph of triples without a graph map, and of rr:defaultGraph.
    pub graph: NamedGraph,
    /// Drop the terms that are data errors (invalid IRIs, values that do not fit the datatype)
    /// with a warning, instead of failing.
    pub ignore_data_errors: bool,
    /// Prefix of the blank node labels, unique per execution.
    pub blank_node_prefix: String,
}

/// A batch of triples: the columns subject, object and, when the predicate is not constant,
/// predicate, with their RDF types.
#[derive(Debug)]
pub struct MappedTriples {
    pub df: DataFrame,
    pub types: HashMap<String, RDFNodeState>,
    pub predicate: Option<NamedNode>,
    pub graph: NamedGraph,
}

/// An evaluated term map: a column of terms, of one RDF type.
#[derive(Clone)]
struct Terms {
    series: Series,
    state: RDFNodeState,
}

enum Evaluated {
    Constant(Term),
    /// Terms per group of rows: literals with datatypes like xsd:dateTime may need one group
    /// per time zone offset. Rows outside a group, or null, give no term.
    Columns(Vec<(Option<Series>, Terms)>),
}

/// The graphs of a batch: constant, or a column of graph IRIs.
enum Graphs {
    Constant(NamedGraph),
    Column(Series),
}

struct Ctx<'a> {
    options: &'a R2RMLOptions,
    warnings: &'a mut Vec<String>,
    /// The base IRI of the triples map that is evaluated: its rml:baseIRI, or that of the options.
    base_iri: String,
    /// A tag for the logical table of the triples map that is evaluated, which keeps the blank
    /// nodes of its records apart from those of other tables.
    record_tag: String,
}

impl Ctx<'_> {
    /// Sets the base IRI and the record tag to those of a triples map, and returns the previous.
    fn enter(&mut self, tm: &TriplesMap) -> (String, String) {
        use std::hash::{Hash, Hasher};
        let mut hasher = std::collections::hash_map::DefaultHasher::new();
        tm.logical_table.key().hash(&mut hasher);
        let base = tm
            .base_iri
            .clone()
            .unwrap_or_else(|| self.options.base_iri.clone());
        (
            std::mem::replace(&mut self.base_iri, base),
            std::mem::replace(&mut self.record_tag, format!("r{:x}_", hasher.finish())),
        )
    }

    fn leave(&mut self, previous: (String, String)) {
        self.base_iri = previous.0;
        self.record_tag = previous.1;
    }

    fn data_error(&mut self, location: &str, msg: String) -> Result<(), R2RMLError> {
        if self.options.ignore_data_errors {
            self.warnings.push(format!("{location}: {msg}"));
            Ok(())
        } else {
            Err(R2RMLError::DataError(location.to_string(), msg))
        }
    }
}

/// Finds the column a column reference names: a delimited identifier ("Name") names the column
/// exactly, a regular identifier names it exactly or, failing that, case insensitively.
pub fn resolve_column<'a>(df: &'a DataFrame, reference: &str, location: &str) -> Result<&'a Column, R2RMLError> {
    let reference = reference.trim();
    let names: Vec<&str> = df.get_column_names().into_iter().map(|x| x.as_str()).collect();
    let found = if reference.len() >= 2 && reference.starts_with('"') && reference.ends_with('"') {
        let unquoted = reference[1..reference.len() - 1].replace("\"\"", "\"");
        names.iter().find(|n| **n == unquoted).copied()
    } else {
        names.iter().find(|n| **n == reference).copied().or_else(|| {
            let matches: Vec<&str> = names
                .iter()
                .filter(|n| n.eq_ignore_ascii_case(reference))
                .copied()
                .collect();
            if matches.len() == 1 {
                Some(matches[0])
            } else {
                None
            }
        })
    };
    match found {
        Some(n) => Ok(df.column(n).unwrap()),
        None => Err(R2RMLError::UndefinedColumn(
            reference.to_string(),
            location.to_string(),
            names.join(", "),
        )),
    }
}

/// The lexical forms of the natural RDF literals of the values of a column.
fn lexical(c: &Column) -> Result<StringChunked, R2RMLError> {
    let s = c.as_materialized_series();
    let out = match s.dtype() {
        DataType::String => s.str()?.clone(),
        DataType::Datetime(..) => s.datetime()?.to_string("%Y-%m-%dT%H:%M:%S%.f")?,
        DataType::Time => s.time()?.to_string("%H:%M:%S%.f")?,
        DataType::Binary => {
            let b = s.binary()?;
            b.iter()
                .map(|v| v.map(hex_upper))
                .collect::<StringChunked>()
        }
        DataType::Float32 | DataType::Float64 => {
            // Canonical xsd:double lexical forms are not needed for IRIs; use shortest round trip.
            s.cast(&DataType::String)?.str()?.clone()
        }
        _ => s.cast(&DataType::String)?.str()?.clone(),
    };
    Ok(out.with_name(c.name().clone()))
}

fn hex_upper(b: &[u8]) -> String {
    const HEX: &[u8; 16] = b"0123456789ABCDEF";
    let mut s = String::with_capacity(b.len() * 2);
    for x in b {
        s.push(HEX[(x >> 4) as usize] as char);
        s.push(HEX[(x & 15) as usize] as char);
    }
    s
}

/// Rows per parallel slice, at least.
const MIN_SLICE: usize = 1 << 16;

/// Row ranges (offset, length) that split n rows over the threads.
fn slices(n: usize) -> Vec<(usize, usize)> {
    let parts = (n / MIN_SLICE).clamp(1, rayon::current_num_threads().max(1));
    let stride = n.div_ceil(parts).max(1);
    let mut out = vec![];
    let mut start = 0;
    while start < n {
        out.push((start, stride.min(n - start)));
        start += stride;
    }
    if out.is_empty() {
        out.push((0, 0));
    }
    out
}

fn concat_strings(parts: Vec<StringChunked>, name: &str) -> Result<StringChunked, R2RMLError> {
    let mut it = parts.into_iter();
    let mut out = it.next().unwrap_or_else(|| StringChunked::full_null(name.into(), 0));
    for p in it {
        out.append(&p)?;
    }
    Ok(out.with_name(name.into()))
}

/// Writes f of each value of a string column, in parallel over slices of rows. Nulls stay null.
fn par_strings<F>(ca: &StringChunked, f: F) -> Result<StringChunked, R2RMLError>
where
    F: Fn(&str, &mut String) + Sync,
{
    let parts: Vec<StringChunked> = slices(ca.len())
        .into_par_iter()
        .map(|(o, l)| ca.slice(o as i64, l).apply_into_string_amortized(|v, buf| f(v, buf)))
        .collect();
    concat_strings(parts, ca.name().as_str())
}

/// Whether f holds for any value of a string column.
fn par_any<F>(ca: &StringChunked, f: F) -> bool
where
    F: Fn(&str) -> bool + Sync,
{
    slices(ca.len())
        .into_par_iter()
        .any(|(o, l)| ca.slice(o as i64, l).iter().flatten().any(&f))
}

fn is_unreserved(b: u8) -> bool {
    b.is_ascii_alphanumeric() || matches!(b, b'-' | b'.' | b'_' | b'~')
}

const HEX_UPPER: &[u8; 16] = b"0123456789ABCDEF";
const HEX_LOWER: &[u8; 16] = b"0123456789abcdef";

/// Whether a character outside ASCII is in the ucschar production of RFC 3987, and so unreserved
/// in IRIs.
fn is_ucschar(c: char) -> bool {
    let c = c as u32;
    matches!(c, 0xA0..=0xD7FF | 0xF900..=0xFDCF | 0xFDF0..=0xFFEF)
        || (0x10000..=0xDFFFD).contains(&c) && (c & 0xFFFF) <= 0xFFFD
        || (0xE1000..=0xEFFFD).contains(&c)
}

/// IRI-safe percent encoding of template values, <https://www.w3.org/TR/r2rml/#dfn-iri-safe>:
/// every character that is not in the iunreserved production of RFC 3987 is percent encoded.
/// With `keep_unicode`, the characters outside ASCII that are unreserved in IRIs are kept, as
/// the definition says. Without it they are encoded as well, which gives URIs (rml:URI).
fn push_iri_safe(v: &str, buf: &mut String, keep_unicode: bool) {
    let mut utf8 = [0u8; 4];
    for c in v.chars() {
        if (c.is_ascii() && is_unreserved(c as u8)) || (keep_unicode && is_ucschar(c)) {
            buf.push(c);
        } else {
            for b in c.encode_utf8(&mut utf8).bytes() {
                buf.push('%');
                buf.push(HEX_UPPER[(b >> 4) as usize] as char);
                buf.push(HEX_UPPER[(b & 15) as usize] as char);
            }
        }
    }
}

/// The IRI-safe form of the lexical forms of a column of the given type. Integers and booleans
/// are IRI-safe as they are, as are strings without reserved characters.
fn iri_safe_column(
    l: StringChunked,
    dtype: &DataType,
    encoding: IriEncoding,
) -> Result<StringChunked, R2RMLError> {
    if encoding == IriEncoding::Unsafe || dtype.is_integer() || dtype == &DataType::Boolean {
        return Ok(l);
    }
    let keep_unicode = encoding == IriEncoding::Safe;
    let is_safe = |v: &str| {
        v.bytes().all(is_unreserved)
            || (keep_unicode
                && v.chars()
                    .all(|c| (c.is_ascii() && is_unreserved(c as u8)) || is_ucschar(c)))
    };
    if !par_any(&l, |v| !is_safe(v)) {
        return Ok(l);
    }
    par_strings(&l, |v, buf| push_iri_safe(v, buf, keep_unicode))
}

/// The values of a language map, a datatype map or one side of a join condition, as strings:
/// the constant, the lexical forms of a column, or a template without encoding of its values.
fn value_strings(
    df: &DataFrame,
    value: &TermValue,
    location: &str,
) -> Result<StringChunked, R2RMLError> {
    Ok(match value {
        TermValue::Constant(t) => {
            let s = match t {
                Term::NamedNode(nn) => nn.as_str().to_string(),
                Term::Literal(l) => l.value().to_string(),
                t => t.to_string(),
            };
            StringChunked::full("v".into(), s.as_str(), df.height())
        }
        TermValue::Column(c) => lexical(resolve_column(df, c, location)?)?,
        TermValue::Record => lexical(record_column(df, location)?)?,
        TermValue::Template(parts) => {
            let mut columns = vec![];
            let mut exprs: Vec<Expr> = vec![];
            for (i, p) in parts.iter().enumerate() {
                match p {
                    TemplatePart::Text(t) => exprs.push(lit(t.clone())),
                    TemplatePart::Column(c) => {
                        let name = format!("_{i}");
                        let l = lexical(resolve_column(df, c, location)?)?;
                        columns.push(l.with_name(name.as_str().into()).into_series().into_column());
                        exprs.push(col(name));
                    }
                }
            }
            if columns.is_empty() {
                StringChunked::full("v".into(), template_shape(parts, "").as_str(), df.height())
            } else {
                let out = DataFrame::new(df.height(), columns)?
                    .lazy()
                    .select([concat_str(exprs, "", false).alias("v")])
                    .collect_auto()?;
                out.column("v")?.str()?.clone()
            }
        }
    })
}

/// The column that identifies the record of each row.
fn record_column<'a>(df: &'a DataFrame, location: &str) -> Result<&'a Column, R2RMLError> {
    df.column(RECORD_COLUMN).map_err(|_| {
        R2RMLError::MappingError(format!(
            "{location} generates a blank node per record, but the logical table has no record column"
        ))
    })
}

/// A column of language tagged strings with one language.
fn language_tagged(strings: &StringChunked, language: &str) -> Result<Series, R2RMLError> {
    let tmp = DataFrame::new(
        strings.len(),
        vec![strings.clone().with_name("v".into()).into_series().into_column()],
    )?;
    let out = tmp
        .lazy()
        .select([as_struct(vec![
            col("v").alias(LANG_STRING_VALUE_FIELD),
            lit(language.to_string()).alias(LANG_STRING_LANG_FIELD),
        ])
        .alias("t")])
        .collect_auto()?;
    Ok(out.column("t")?.as_materialized_series().clone())
}

/// The distinct values of the keys, with the strings of the rows of each: the rows of other
/// keys are null. Rows without a key are left out.
fn by_key(strings: &StringChunked, keys: &StringChunked) -> Vec<(String, StringChunked)> {
    let distinct: BTreeSet<&str> = keys.iter().flatten().collect();
    distinct
        .into_iter()
        .map(|k| {
            let of_key: StringChunked = strings
                .iter()
                .zip(keys.iter())
                .map(|(s, key)| if key == Some(k) { s } else { None })
                .collect();
            (k.to_string(), of_key.with_name(strings.name().clone()))
        })
        .collect()
}


/// Blank node labels: the prefix, then the value with characters other than ASCII letters and
/// digits escaped as _xx.
fn push_blank_label(prefix: &str, v: &str, buf: &mut String) {
    buf.push_str(prefix);
    for b in v.bytes() {
        if b.is_ascii_alphanumeric() {
            buf.push(b as char);
        } else {
            buf.push('_');
            buf.push(HEX_LOWER[(b >> 4) as usize] as char);
            buf.push(HEX_LOWER[(b & 15) as usize] as char);
        }
    }
}

/// The template with each column reference replaced by fill.
fn template_shape(parts: &[TemplatePart], fill: &str) -> String {
    parts
        .iter()
        .map(|p| match p {
            TemplatePart::Text(t) => t.as_str(),
            TemplatePart::Column(_) => fill,
        })
        .collect()
}

/// Whether an IRI template with IRI-safe values always gives valid absolute IRIs, so that they
/// need not be checked one by one. This holds when the text before the first column has a
/// scheme and, if it has an authority, ends the authority: the values then are in the path,
/// query or fragment, where unreserved characters and percent encodings are always allowed.
fn template_gives_valid_iris(parts: &[TemplatePart]) -> bool {
    if !parts.iter().any(|p| matches!(p, TemplatePart::Column(_))) {
        return false;
    }
    let prefix: String = parts
        .iter()
        .map_while(|p| match p {
            TemplatePart::Text(t) => Some(t.as_str()),
            TemplatePart::Column(_) => None,
        })
        .collect();
    let Some(colon) = prefix.find(':') else {
        return false;
    };
    let scheme = &prefix[..colon];
    if scheme.is_empty() || scheme.contains(['/', '?', '#']) {
        return false;
    }
    let after_authority = match prefix[colon + 1..].strip_prefix("//") {
        Some(authority) => authority.contains(['/', '?', '#']),
        None => true,
    };
    after_authority
        && ["a", "", "%41", "a.b-c_d~e"]
            .iter()
            .all(|fill| Iri::parse(template_shape(parts, fill).as_str()).is_ok())
}

fn state(t: BaseRDFNodeType) -> RDFNodeState {
    t.into_default_input_rdf_node_state()
}

fn evaluate(
    ctx: &mut Ctx,
    tm: &TermMap,
    df: &DataFrame,
    location: &str,
) -> Result<Evaluated, R2RMLError> {
    // Whether the strings are known to be valid absolute IRIs, from the shape of the template.
    let mut valid_iris = false;
    let strings: StringChunked = match &tm.value {
        TermValue::Constant(t) => return Ok(Evaluated::Constant(t.clone())),
        TermValue::Record => {
            // The record, tagged with its logical table.
            let records = lexical(record_column(df, location)?)?;
            let tag = ctx.record_tag.as_str();
            par_strings(&records, |v, buf| {
                buf.push_str(tag);
                buf.push_str(v);
            })?
        }
        TermValue::Column(c) => {
            let column = resolve_column(df, c, location)?;
            if tm.term_type == TermType::Literal
                && tm.language.is_none()
                && tm.datatype.is_none()
                && tm.language_map.is_none()
                && tm.datatype_map.is_none()
            {
                return Ok(Evaluated::Columns(vec![(None, natural_literal(column)?)]));
            }
            lexical(column)?
        }
        TermValue::Template(parts) => {
            let mut parts: Vec<TemplatePart> = parts.clone();
            // Values that are not encoded can make any template invalid.
            if tm.term_type == TermType::IRI && tm.iri_encoding != IriEncoding::Unsafe {
                if template_gives_valid_iris(&parts) {
                    valid_iris = true;
                } else if !parts
                    .iter()
                    .any(|p| matches!(p, TemplatePart::Text(t) if t.contains(':')))
                {
                    // IRI-safe values have no colon, so without one in the text the IRIs are
                    // all relative, and resolved against the base IRI.
                    let mut with_base = vec![TemplatePart::Text(ctx.base_iri.clone())];
                    with_base.extend(parts.iter().cloned());
                    if template_gives_valid_iris(&with_base) {
                        parts = with_base;
                        valid_iris = true;
                    }
                }
            }
            let mut lf_cols = vec![];
            let mut exprs: Vec<Expr> = vec![];
            for (i, p) in parts.iter().enumerate() {
                match p {
                    TemplatePart::Text(t) => exprs.push(lit(t.clone())),
                    TemplatePart::Column(c) => {
                        let column = resolve_column(df, c, location)?;
                        let mut l = lexical(column)?;
                        if tm.term_type == TermType::IRI {
                            l = iri_safe_column(l, column.dtype(), tm.iri_encoding)?;
                        }
                        let name = format!("_{i}");
                        lf_cols.push(l.with_name(name.as_str().into()).into_series().into_column());
                        exprs.push(col(name));
                    }
                }
            }
            if lf_cols.is_empty() {
                // A template without columns gives the same string for each row.
                let s: String = template_shape(&parts, "");
                StringChunked::full("t".into(), s.as_str(), df.height())
            } else if exprs.len() == 1 {
                lf_cols.pop().unwrap().as_materialized_series().str()?.clone()
            } else {
                let tmp = DataFrame::new(df.height(), lf_cols)?;
                let out = tmp
                    .lazy()
                    .select([concat_str(exprs, "", false).alias("t")])
                    .collect_auto()?;
                out.column("t")?.str()?.clone()
            }
        }
    };
    match tm.term_type {
        TermType::IRI => {
            let resolved = if valid_iris {
                strings
            } else {
                resolve_iris(ctx, strings, location)?
            };
            Ok(Evaluated::Columns(vec![(
                None,
                Terms {
                    series: resolved.into_series(),
                    state: state(BaseRDFNodeType::IRI),
                },
            )]))
        }
        TermType::BlankNode => {
            let prefix = ctx.options.blank_node_prefix.as_str();
            let labels = par_strings(&strings, |v, buf| push_blank_label(prefix, v, buf))?;
            Ok(Evaluated::Columns(vec![(
                None,
                Terms {
                    series: labels.into_series(),
                    state: state(BaseRDFNodeType::BlankNode),
                },
            )]))
        }
        TermType::Literal => {
            let lang_state = || state(BaseRDFNodeType::Literal(rdf::LANG_STRING.into_owned(), None));
            if let Some(language_map) = &tm.language_map {
                // A group of literals per language of the language map.
                let keys = value_strings(df, language_map, location)?;
                let mut groups = vec![];
                for (language, of_language) in by_key(&strings, &keys) {
                    if oxilangtag::LanguageTag::parse(language.as_str()).is_err() {
                        ctx.data_error(location, format!("the invalid language tag {language:?}"))?;
                        continue;
                    }
                    groups.push((
                        Some(of_language.is_not_null().into_series()),
                        Terms {
                            series: language_tagged(&of_language, &language)?,
                            state: lang_state(),
                        },
                    ));
                }
                return Ok(Evaluated::Columns(groups));
            }
            if let Some(datatype_map) = &tm.datatype_map {
                // A group of literals per datatype of the datatype map.
                let keys = value_strings(df, datatype_map, location)?;
                let mut groups = vec![];
                for (datatype, of_datatype) in by_key(&strings, &keys) {
                    let iri = if Iri::parse(datatype.as_str()).is_ok() {
                        datatype
                    } else {
                        format!("{}{datatype}", ctx.base_iri)
                    };
                    let Ok(datatype) = NamedNode::new(iri.as_str()) else {
                        ctx.data_error(location, format!("the invalid datatype IRI {iri:?}"))?;
                        continue;
                    };
                    if let Evaluated::Columns(g) = typed_literals(ctx, &of_datatype, &datatype, location)? {
                        groups.extend(g);
                    }
                }
                return Ok(Evaluated::Columns(groups));
            }
            if let Some(l) = &tm.language {
                // Null values give null structs.
                let mask = if strings.null_count() > 0 {
                    Some(strings.is_not_null().into_series())
                } else {
                    None
                };
                let s = language_tagged(&strings, l)?;
                return Ok(Evaluated::Columns(vec![(
                    mask,
                    Terms {
                        series: s,
                        state: lang_state(),
                    },
                )]));
            }
            let datatype = tm
                .datatype
                .clone()
                .unwrap_or_else(|| xsd::STRING.into_owned());
            typed_literals(ctx, &strings, &datatype, location)
        }
    }
}

/// Checks that the strings are IRIs, and resolves the relative ones against the base IRI.
/// Strings that are not IRIs either way are data errors, and give no term.
fn resolve_iris(
    ctx: &mut Ctx,
    strings: StringChunked,
    location: &str,
) -> Result<StringChunked, R2RMLError> {
    let base = ctx.base_iri.clone();
    let base = base.as_str();
    let parts: Vec<(StringChunked, Vec<String>)> = slices(strings.len())
        .into_par_iter()
        .map(|(o, l)| {
            let s = strings.slice(o as i64, l);
            if s.iter().flatten().all(|v| Iri::parse(v).is_ok()) {
                return (s, vec![]);
            }
            let mut errors = vec![];
            let out: StringChunked = s
                .iter()
                .map(|v| {
                    v.and_then(|v| {
                        if Iri::parse(v).is_ok() {
                            Some(v.to_string())
                        } else {
                            let joined = format!("{base}{v}");
                            if Iri::parse(joined.as_str()).is_ok() {
                                Some(joined)
                            } else {
                                if errors.len() < 5 {
                                    errors.push(v.to_string());
                                }
                                None
                            }
                        }
                    })
                })
                .collect();
            (out, errors)
        })
        .collect();
    let mut errors = vec![];
    let mut cas = vec![];
    for (ca, e) in parts {
        cas.push(ca);
        errors.extend(e);
    }
    errors.truncate(5);
    if !errors.is_empty() {
        ctx.data_error(location, format!("invalid IRIs, e.g. {}", errors.join(", ")))?;
    }
    concat_strings(cas, strings.name().as_str())
}

/// Literals with the given datatype from their lexical forms. Values that are null, or not
/// valid for the datatype (data errors), give null terms.
fn typed_literals(
    ctx: &mut Ctx,
    strings: &StringChunked,
    datatype: &NamedNode,
    location: &str,
) -> Result<Evaluated, R2RMLError> {
    let plain = BaseRDFNodeType::Literal(datatype.clone(), None);
    if matches!(SeriesBuilder::new(&plain), SeriesBuilder::String(..)) {
        // Stored by the lexical form: the strings are the terms.
        return Ok(Evaluated::Columns(vec![(
            None,
            Terms {
                series: strings.clone().with_name("t".into()).into_series(),
                state: state(plain),
            },
        )]));
    }
    let ranges = slices(strings.len());
    // The time zone offset is part of the type of xsd:dateTime literals, so there is one column
    // of terms per offset.
    let has_zones = matches!(datatype.as_ref(), xsd::DATE_TIME | xsd::DATE_TIME_STAMP);
    let zones_per_row: Vec<Vec<Option<i16>>> = if has_zones {
        ranges
            .par_iter()
            .map(|(o, l)| {
                strings
                    .slice(*o as i64, *l)
                    .iter()
                    .map(|v| v.and_then(|v| literal_time_zone(v, datatype.as_ref())))
                    .collect()
            })
            .collect()
    } else {
        vec![]
    };
    let zones: BTreeSet<Option<i16>> = if has_zones {
        zones_per_row
            .par_iter()
            .zip(ranges.par_iter())
            .map(|(z, (o, l))| {
                let s = strings.slice(*o as i64, *l);
                z.iter()
                    .zip(s.iter())
                    .filter(|(_, v)| v.is_some())
                    .map(|(z, _)| *z)
                    .collect::<BTreeSet<_>>()
            })
            .reduce(BTreeSet::new, |mut a, b| {
                a.extend(b);
                a
            })
    } else {
        BTreeSet::from([None])
    };
    let mut out = vec![];
    let mut bad = vec![];
    for tz in zones {
        let t = BaseRDFNodeType::Literal(datatype.clone(), tz);
        let parts: Vec<(Series, Vec<String>)> = ranges
            .par_iter()
            .enumerate()
            .map(|(k, (o, l))| {
                let mut builder = SeriesBuilder::new_with_capacity(&t, *l);
                let mut bad = vec![];
                for (i, v) in strings.slice(*o as i64, *l).iter().enumerate() {
                    match v {
                        Some(v) if !has_zones || zones_per_row[k][i] == tz => {
                            if builder.parse_literal(v, None).is_err() {
                                if bad.len() < 5 {
                                    bad.push(v.to_string());
                                }
                                builder.push_none();
                            }
                        }
                        _ => builder.push_none(),
                    }
                }
                (builder.into_series("t"), bad)
            })
            .collect();
        let mut series: Option<Series> = None;
        for (p, b) in parts {
            bad.extend(b);
            match &mut series {
                None => series = Some(p),
                Some(s) => {
                    s.append(&p)?;
                }
            }
        }
        out.push((
            None,
            Terms {
                series: series.unwrap(),
                state: state(t),
            },
        ));
    }
    bad.truncate(5);
    if !bad.is_empty() {
        ctx.data_error(
            location,
            format!("values that are not valid {datatype}, e.g. {}", bad.join(", ")),
        )?;
    }
    Ok(Evaluated::Columns(out))
}

/// The natural RDF literals of a column, <https://www.w3.org/TR/r2rml/#natural-mapping>.
fn natural_literal(c: &Column) -> Result<Terms, R2RMLError> {
    let s = c.as_materialized_series();
    let literal = |dt: oxrdf::NamedNodeRef| state(BaseRDFNodeType::Literal(dt.into_owned(), None));
    Ok(match s.dtype() {
        DataType::String | DataType::Null | DataType::Categorical(..) | DataType::Enum(..) => Terms {
            series: s.cast(&DataType::String)?,
            state: literal(xsd::STRING),
        },
        DataType::Int8
        | DataType::Int16
        | DataType::Int32
        | DataType::Int64
        | DataType::UInt8
        | DataType::UInt16
        | DataType::UInt32
        | DataType::UInt64 => Terms {
            series: s.cast(&DataType::Int64)?,
            state: literal(xsd::INTEGER),
        },
        // Through the shortest decimal representation, so that a REAL 70.22 stays 70.22.
        DataType::Float32 => Terms {
            series: s.cast(&DataType::String)?.cast(&DataType::Float64)?,
            state: literal(xsd::DOUBLE),
        },
        DataType::Float64 => Terms {
            series: s.clone(),
            state: literal(xsd::DOUBLE),
        },
        DataType::Boolean => Terms {
            series: s.clone(),
            state: literal(xsd::BOOLEAN),
        },
        DataType::Binary => Terms {
            series: lexical(c)?.into_series(),
            state: literal(xsd::HEX_BINARY),
        },
        DataType::Time => Terms {
            series: lexical(c)?.into_series(),
            state: literal(xsd::TIME),
        },
        DataType::Datetime(tu, _) if *tu != TimeUnit::Nanoseconds => match polars_type_to_literal_type(s.dtype()) {
            Ok(st) => Terms {
                series: s.clone(),
                state: st,
            },
            Err(_) => Terms {
                series: lexical(c)?.into_series(),
                state: literal(xsd::DATE_TIME),
            },
        },
        // DECIMAL and NUMERIC columns with a scale are xsd:decimal, stored with maplib's
        // precision and scale. Values that do not fit are an error rather than dropped.
        DataType::Decimal(_, scale) if *scale != 0 => Terms {
            series: s.strict_cast(&default_decimal_type())?,
            state: literal(xsd::DECIMAL),
        },
        dt => match polars_type_to_literal_type(dt) {
            Ok(st) => Terms {
                series: s.clone(),
                state: st,
            },
            Err(_) => Terms {
                series: lexical(c)?.into_series(),
                state: literal(xsd::STRING),
            },
        },
    })
}

fn evaluate_graphs(
    ctx: &mut Ctx,
    graphs: &[&TermMap],
    df: &DataFrame,
    location: &str,
) -> Result<Vec<Graphs>, R2RMLError> {
    if graphs.is_empty() {
        return Ok(vec![Graphs::Constant(ctx.options.graph.clone())]);
    }
    let mut out = vec![];
    for g in graphs {
        if g.is_default_graph() {
            out.push(Graphs::Constant(ctx.options.graph.clone()));
            continue;
        }
        match evaluate(ctx, g, df, location)? {
            Evaluated::Constant(Term::NamedNode(nn)) => out.push(Graphs::Constant(NamedGraph::NamedGraph(nn))),
            Evaluated::Constant(t) => {
                return Err(R2RMLError::MappingError(format!("the graph {t} must be an IRI")))
            }
            Evaluated::Columns(mut c) => out.push(Graphs::Column(c.pop().unwrap().1.series)),
        }
    }
    Ok(out)
}

/// Adds batches for subject column `subjects`, predicate and object, in each of the graphs.
#[allow(clippy::too_many_arguments)]
fn emit(
    out: &mut Vec<MappedTriples>,
    subjects: &Terms,
    predicate: &Evaluated,
    object: &Evaluated,
    graphs: &[Graphs],
    height: usize,
    location: &str,
    options: &R2RMLOptions,
) -> Result<(), R2RMLError> {
    let (predicate_const, predicate_terms) = match predicate {
        Evaluated::Constant(Term::NamedNode(nn)) => (Some(nn.clone()), None),
        Evaluated::Constant(t) => {
            return Err(R2RMLError::MappingError(format!("the predicate {t} in {location} must be an IRI")))
        }
        Evaluated::Columns(c) => (None, Some(c[0].1.clone())),
    };
    let object_groups: Vec<(Option<Series>, Terms)> = match object {
        Evaluated::Constant(t) => vec![(None, constant_terms(t, height)?)],
        Evaluated::Columns(c) => c.clone(),
    };
    for (mask, objects) in object_groups {
        for g in graphs {
            let mut cols = vec![
                subjects.series.clone().with_name(SUBJECT_COL_NAME.into()).into_column(),
                objects.series.clone().with_name(OBJECT_COL_NAME.into()).into_column(),
            ];
            let mut types = HashMap::from([
                (SUBJECT_COL_NAME.to_string(), subjects.state.clone()),
                (OBJECT_COL_NAME.to_string(), objects.state.clone()),
            ]);
            if let Some(p) = &predicate_terms {
                cols.push(p.series.clone().with_name(PREDICATE_COL_NAME.into()).into_column());
                types.insert(PREDICATE_COL_NAME.to_string(), p.state.clone());
            }
            let mut filter = col(SUBJECT_COL_NAME)
                .is_not_null()
                .and(col(OBJECT_COL_NAME).is_not_null());
            let mut has_nulls =
                subjects.series.null_count() > 0 || objects.series.null_count() > 0;
            if let Some(p) = &predicate_terms {
                filter = filter.and(col(PREDICATE_COL_NAME).is_not_null());
                has_nulls |= p.series.null_count() > 0;
            }
            if let Some(m) = &mask {
                cols.push(m.clone().with_name("_mask".into()).into_column());
                filter = filter.and(col("_mask"));
            }
            if let Graphs::Column(gs) = g {
                cols.push(gs.clone().with_name(GRAPH_COL.into()).into_column());
                filter = filter.and(col(GRAPH_COL).is_not_null());
                has_nulls |= gs.null_count() > 0;
            }
            let df = DataFrame::new(height, cols)?;
            // Filtering copies every column, so only when there is something to filter out.
            let df = if has_nulls || mask.is_some() {
                df.lazy()
                    .filter(filter)
                    .drop(polars::prelude::by_name(["_mask"], false, false))
                    .collect_auto()?
            } else {
                df
            };
            if df.height() == 0 {
                continue;
            }
            match g {
                Graphs::Constant(graph) => out.push(MappedTriples {
                    df,
                    types,
                    predicate: predicate_const.clone(),
                    graph: graph.clone(),
                }),
                Graphs::Column(_) => {
                    for mut part in df.partition_by([GRAPH_COL], true)? {
                        let name = part
                            .column(GRAPH_COL)?
                            .str()?
                            .get(0)
                            .map(|x| x.to_string());
                        let _ = part.drop_in_place(GRAPH_COL)?;
                        let Some(name) = name else { continue };
                        out.push(MappedTriples {
                            df: part,
                            types: types.clone(),
                            predicate: predicate_const.clone(),
                            graph: NamedGraph::NamedGraph(NamedNode::new_unchecked(name)),
                        });
                    }
                }
            }
        }
    }
    let _ = options;
    Ok(())
}

fn constant_terms(t: &Term, height: usize) -> Result<Terms, R2RMLError> {
    match t {
        Term::NamedNode(nn) => Ok(Terms {
            series: StringChunked::full("c".into(), nn.as_str(), height).into_series(),
            state: state(BaseRDFNodeType::IRI),
        }),
        Term::Literal(l) => {
            if let Some(lang) = l.language() {
                let tmp = DataFrame::new(height, vec![Column::new_scalar("_".into(), polars::prelude::Scalar::null(DataType::Null), height)])?;
                let out = tmp
                    .lazy()
                    .select([as_struct(vec![
                        lit(l.value().to_string()).alias(LANG_STRING_VALUE_FIELD),
                        lit(lang.to_string()).alias(LANG_STRING_LANG_FIELD),
                    ])
                    .alias("t")])
                    .collect_auto()?;
                let s = out.column("t")?.as_materialized_series().new_from_index(0, height);
                Ok(Terms {
                    series: s,
                    state: state(BaseRDFNodeType::Literal(rdf::LANG_STRING.into_owned(), None)),
                })
            } else {
                let dt = l.datatype().into_owned();
                let tz = literal_time_zone(l.value(), dt.as_ref());
                let bt = BaseRDFNodeType::Literal(dt, tz);
                let mut b = SeriesBuilder::new_with_capacity(&bt, 1);
                b.parse_literal(l.value(), None).map_err(|e| {
                    R2RMLError::MappingError(format!("the constant {l} can not be stored: {e}"))
                })?;
                Ok(Terms {
                    series: b.into_series("c").new_from_index(0, height),
                    state: state(bt),
                })
            }
        }
        t => Err(R2RMLError::MappingError(format!("the constant {t} must be an IRI or a literal"))),
    }
}

fn subject_terms(ctx: &mut Ctx, tm: &TriplesMap, df: &DataFrame) -> Result<Terms, R2RMLError> {
    let location = format!("the subject map of {}", tm.name);
    // The subjects of a parent triples map have its base IRI, not that of the child.
    let previous = ctx.enter(tm);
    let evaluated = evaluate(ctx, &tm.subject_map, df, &location);
    ctx.leave(previous);
    match evaluated? {
        Evaluated::Constant(t) => constant_terms(&t, df.height()),
        Evaluated::Columns(mut c) => Ok(c.pop().unwrap().1),
    }
}

/// Renames the columns of a DataFrame with a prefix, so that two tables can be joined.
fn prefixed(df: &DataFrame, prefix: &str) -> Result<DataFrame, R2RMLError> {
    let cols: Vec<Column> = df
        .columns()
        .iter()
        .map(|c| c.clone().with_name(format!("{prefix}{}", c.name()).into()))
        .collect();
    Ok(DataFrame::new(df.height(), cols)?)
}

/// Joins the child and parent logical tables on the join conditions, giving a DataFrame with
/// the child columns as they are and the parent columns prefixed with "\u{1}p:".
fn join_tables(
    child: &DataFrame,
    parent: &DataFrame,
    r: &RefObjectMap,
    child_references: &[&str],
    parent_references: &[&str],
    location: &str,
) -> Result<DataFrame, R2RMLError> {
    const P: &str = "\u{1}p:";
    // Only the columns the term maps evaluated on the joined table reference are joined.
    let project = |df: &DataFrame, references: &[&str]| -> Result<DataFrame, R2RMLError> {
        let mut names: Vec<polars::prelude::PlSmallStr> = vec![];
        for c in references {
            let name = resolve_column(df, c, location)?.name().clone();
            if !names.contains(&name) {
                names.push(name);
            }
        }
        Ok(df.select(names)?)
    };
    let mut left = project(child, child_references)?;
    let mut right = prefixed(&project(parent, parent_references)?, P)?;
    let mut left_on = vec![];
    let mut right_on = vec![];
    for (i, (c, p)) in r.join_conditions.iter().enumerate() {
        let (cs, ps) = match (c, p) {
            (TermValue::Column(c), TermValue::Column(p)) => {
                let cc = resolve_column(child, c, location)?;
                let pc = resolve_column(parent, p, location)?;
                if cc.dtype() == pc.dtype() {
                    (cc.as_materialized_series().clone(), pc.as_materialized_series().clone())
                } else if cc.dtype().is_primitive_numeric() && pc.dtype().is_primitive_numeric() {
                    // Numbers are compared as numbers, as in SQL.
                    let t = if cc.dtype().is_float() || pc.dtype().is_float() {
                        DataType::Float64
                    } else {
                        DataType::Int64
                    };
                    (
                        cc.as_materialized_series().cast(&t)?,
                        pc.as_materialized_series().cast(&t)?,
                    )
                } else {
                    (lexical(cc)?.into_series(), lexical(pc)?.into_series())
                }
            }
            // The values of child and parent maps are compared as strings.
            _ => (
                value_strings(child, c, location)?.into_series(),
                value_strings(parent, p, location)?.into_series(),
            ),
        };
        let ln = format!("\u{1}jc{i}");
        let rn = format!("\u{1}jp{i}");
        left.with_column(cs.with_name(ln.as_str().into()).into_column())?;
        right.with_column(ps.with_name(rn.as_str().into()).into_column())?;
        left_on.push(col(ln));
        right_on.push(col(rn));
    }
    Ok(left
        .lazy()
        .join(right.lazy(), left_on, right_on, JoinArgs::new(JoinType::Inner))?
        .collect_auto()?)
}

/// Evaluates the parent subject map on the joined table, where the parent columns are prefixed.
fn parent_subjects(
    ctx: &mut Ctx,
    parent: &TriplesMap,
    joined: &DataFrame,
) -> Result<Terms, R2RMLError> {
    const P: &str = "\u{1}p:";
    let cols: Vec<Column> = joined
        .columns()
        .iter()
        .filter_map(|c| {
            c.name()
                .strip_prefix(P)
                .map(|n| c.clone().with_name(n.into()))
        })
        .collect();
    let parent_df = DataFrame::new(joined.height(), cols)?;
    subject_terms(ctx, parent, &parent_df)
}

/// Executes the mapping over the results of its logical table queries, keyed by
/// LogicalTable::sql. Returns the triples, and the warnings.
pub fn execute(
    mapping: &R2RMLMapping,
    tables: &HashMap<String, DataFrame>,
    options: &R2RMLOptions,
) -> Result<(Vec<MappedTriples>, Vec<String>), R2RMLError> {
    let mut warnings = vec![];
    let mut out = vec![];
    let mut ctx = Ctx {
        options,
        warnings: &mut warnings,
        base_iri: options.base_iri.clone(),
        record_tag: String::new(),
    };
    // Blank nodes per record need a column that identifies the record of each row: tables that
    // come without one get the row number.
    let with_records: HashMap<String, DataFrame>;
    let tables = if mapping.uses_record() {
        let mut numbered = HashMap::with_capacity(tables.len());
        for (k, df) in tables {
            let df = if df.width() == 0 || df.column(RECORD_COLUMN).is_ok() {
                df.clone()
            } else {
                df.with_row_index(RECORD_COLUMN.into(), None)?
            };
            numbered.insert(k.clone(), df);
        }
        with_records = numbered;
        &with_records
    } else {
        tables
    };
    let table = |lt: &LogicalTable| -> Result<&DataFrame, R2RMLError> {
        tables
            .get(&lt.sql())
            .ok_or_else(|| R2RMLError::MissingTable(lt.sql()))
    };
    for tm in &mapping.triples_maps {
        let df = table(&tm.logical_table)?;
        let height = df.height();
        if height == 0 {
            // An empty result (which may come without columns) gives no triples.
            continue;
        }
        // The term maps of this triples map have its base IRI and record tag.
        let _ = ctx.enter(tm);
        let subjects = subject_terms(&mut ctx, tm, df)?;
        let subject_location = format!("the subject map of {}", tm.name);
        let subject_graph_maps: Vec<&TermMap> = tm.subject_graphs.iter().collect();
        if !tm.classes.is_empty() {
            let graphs = evaluate_graphs(&mut ctx, &subject_graph_maps, df, &subject_location)?;
            for c in &tm.classes {
                emit(
                    &mut out,
                    &subjects,
                    &Evaluated::Constant(Term::NamedNode(rdf::TYPE.into_owned())),
                    &Evaluated::Constant(Term::NamedNode(c.clone())),
                    &graphs,
                    height,
                    &subject_location,
                    options,
                )?;
            }
        }
        for (k, pom) in tm.predicate_object_maps.iter().enumerate() {
            let location = format!("predicate-object map {} of {}", k + 1, tm.name);
            let graph_maps: Vec<&TermMap> = subject_graph_maps
                .iter()
                .copied()
                .chain(pom.graphs.iter())
                .collect();
            let predicates = pom
                .predicates
                .iter()
                .map(|p| evaluate(&mut ctx, p, df, &location))
                .collect::<Result<Vec<_>, _>>()?;
            let mut graphs: Option<Vec<Graphs>> = None;
            for om in &pom.objects {
                match om {
                    ObjectMap::Term(otm) => {
                        if graphs.is_none() {
                            graphs = Some(evaluate_graphs(&mut ctx, &graph_maps, df, &location)?);
                        }
                        let object = evaluate(&mut ctx, otm, df, &location)?;
                        for p in &predicates {
                            emit(&mut out, &subjects, p, &object, graphs.as_ref().unwrap(), height, &location, options)?;
                        }
                    }
                    ObjectMap::Ref(r) => {
                        let parent = &mapping.triples_maps[r.parent];
                        if r.join_conditions.is_empty() {
                            if graphs.is_none() {
                                graphs = Some(evaluate_graphs(&mut ctx, &graph_maps, df, &location)?);
                            }
                            let objects = subject_terms(&mut ctx, parent, df)?;
                            let object = Evaluated::Columns(vec![(None, objects)]);
                            for p in &predicates {
                                emit(&mut out, &subjects, p, &object, graphs.as_ref().unwrap(), height, &location, options)?;
                            }
                        } else {
                            let parent_df = table(&parent.logical_table)?;
                            if parent_df.height() == 0 {
                                continue;
                            }
                            let child_references: Vec<&str> = std::iter::once(&tm.subject_map)
                                .chain(graph_maps.iter().copied())
                                .chain(pom.predicates.iter())
                                .flat_map(|t| t.columns())
                                .collect();
                            let parent_references = parent.subject_map.columns();
                            let joined = join_tables(
                                df,
                                parent_df,
                                r,
                                &child_references,
                                &parent_references,
                                &location,
                            )?;
                            let jh = joined.height();
                            let child_subjects = subject_terms(&mut ctx, tm, &joined)?;
                            let objects = parent_subjects(&mut ctx, parent, &joined)?;
                            let jgraphs = evaluate_graphs(&mut ctx, &graph_maps, &joined, &location)?;
                            let jpredicates = pom
                                .predicates
                                .iter()
                                .map(|p| evaluate(&mut ctx, p, &joined, &location))
                                .collect::<Result<Vec<_>, _>>()?;
                            let object = Evaluated::Columns(vec![(None, objects)]);
                            for p in &jpredicates {
                                emit(&mut out, &child_subjects, p, &object, &jgraphs, jh, &location, options)?;
                            }
                        }
                    }
                }
            }
        }
    }
    for w in &warnings {
        warn!("R2RML: {w}");
    }
    Ok((out, warnings))
}
