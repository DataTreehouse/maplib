//! Executes R2RML mappings column-wise over polars DataFrames.
//!
//! Each term map is evaluated once per logical table into a whole column (templates with
//! `concat_str`, IRI-safe encoding and IRI resolution as one pass over the values), and each
//! combination of predicate map, object map and graph map gives one batch of triples with a
//! constant predicate where possible. The batches are added through maplib's ottr:Triple
//! expansion, as Model.map_triples does, so no rows are handled one by one in Python and the
//! triples of a predicate are added together.

