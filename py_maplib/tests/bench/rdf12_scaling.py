"""Benchmark: how statements about statements scale, to find and verify fixes of scaling issues.

rdf12_benchmark.py compares encodings at a few sizes. This benchmark asks how each cost grows
with the size of the store, which is what decides whether triple terms hold up at billions of
triples when only tens of millions fit on the machine measuring them. Each measurement is made
at several sizes, and the slope of log(cost) against log(size) is reported:

- slope 0: the cost does not grow with the store (a lookup of one statement, a small insert)
- slope 1: the cost grows in proportion (loading, a query whose answer grows with the store)

A slope well above what the operation needs is a scaling issue. Each scenario names the issue
it checks; see the issue overview of the triple term work.

    python rdf12_scaling.py run --triples 1e6,1e7 --label baseline
    python rdf12_scaling.py run --triples 1e6,1e7,3e7 --configs hot --label hot
    python rdf12_scaling.py compare rdf12_results/scaling-baseline.json rdf12_results/scaling-fix.json

Graphs (--configs), generated by rdf12_benchmark.generate:
- uniform: 16 predicates, 10% of the triples described, spread over all predicates (the graph
  of rdf12_benchmark.py)
- hot: 4 predicates, every triple of ex:p0 described, so the statements are a quarter of the
  triples and their triple terms are one partition of the dictionary
- wide: 2000 predicates, 10% of the triples described, so the dictionary has 2000 partitions

Encodings (--encodings): reification (rdf:subject, rdf:predicate, rdf:object) and rdf12
(rdf:reifies with a triple term). The same questions are asked of both, and the number of rows
must agree.

Measurements, per graph, encoding and size, each in a fresh process:
- load: Model.read in batches of --batch-size triples (1M by default; the default of
  Model.read is 10M, which reads files up to 10M triples in one batch and hides costs that grow
  with each batch). Memory held by maplib, and the peak memory of the process.
- insert: the median time to add 10 new statements about ex:p0 (the predicate described in
  every graph), and as controls 10 statements about a predicate with no statements, and 10
  plain triples of ex:p0.
- lookups: queries whose answer has a few rows whatever the size, which should not grow, and
  queries whose answer grows with the store, which should grow no faster than it.
- delete: deleting every statement (and its annotations), then compacting. Memory should fall
  back to what the asserted triples need, as it does for reification.

Build maplib in release mode (maturin develop --release) before measuring; as in
rdf12_benchmark.py, the run refuses to start during builds or with a stale build.
"""

import argparse
import json
import math
import os
import statistics
import subprocess
import sys
import time
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

import rdf12_benchmark as base  # noqa: E402

EX, RDF = base.EX, base.RDF
PREFIXES = base.PREFIXES
ENCODINGS = ["reification", "rdf12"]
CONFIGS = {
    "uniform": {"predicates": 16, "reified": 0.1, "described_predicates": None},
    "hot": {"predicates": 4, "reified": 1.0, "described_predicates": 1},
    "wide": {"predicates": 2000, "reified": 0.1, "described_predicates": None},
}
BATCH_SIZE = 1_000_000
INSERT_ROUNDS = 20
INSERT_SIZE = 10
# What each measurement should cost as the store grows (see the module documentation), and the
# issue of the overview it checks.
EXPECTED = {
    "load_s": (1, "#1 #2 load per batch"),
    "insert_same_predicate_ms": (0, "#1 insert into a large partition"),
    "insert_new_predicate_ms": (0, "control: insert into a new partition"),
    "insert_plain_ms": (0, "control: plain triples"),
    "q:id_var_pred": (0, "#5 #6 reifier known, variable predicate"),
    "q:id_const_pred": (0, "#5 reifier known, constant predicate"),
    "q:subject_var_pred": (0, "#6 #7 subject known, variable predicate"),
    "q:subject_const_pred": (0, "#7 #8 subject known, constant predicate"),
    "q:values_50_subjects": (0, "#9 ids pushed down to rdf:reifies"),
    "q:join_asserted": (1, "#10 more ids than are pushed down"),
    "q:all_statements": (1, "#12 decoding a large answer"),
    "q:all_triple_terms": (1, "#12 decoding triple terms"),
    "delete_s": (1, "deleting every statement"),
}


# ---------------------------------------------------------------------------------------------
# The statements of a graph
# ---------------------------------------------------------------------------------------------


def is_described(i: int, n: int, config: dict, seed: int) -> bool:
    """Whether triple i is described, as rdf12_benchmark.generate decides it."""
    threshold = int(config["reified"] * 1_000_000)
    g = base.mix32(i, seed, 0x85EBCA6B)
    pj = i % config["predicates"]
    dp = config["described_predicates"]
    return g % 1_000_000 < threshold and (dp is None or pj < dp)


def a_described_triple(n: int, config: dict, seed: int) -> dict:
    """A described triple in the middle of the graph: its statement, subject and predicate."""
    preds = config["predicates"]
    for i in range(n // 2, n):
        if is_described(i, n, config, seed):
            return {
                "stmt": f"<{EX}stmt/{i}>",
                "subject": f"<{EX}e/{i // preds}>",
                "predicate": f"<{EX}p{i % preds}>",
            }
    raise ValueError("no described triple")


def statement(encoding: str, r: str, s: str, p: str, o: str) -> str:
    return base.statement_pattern(encoding, r, s, p, o)


def queries(encoding: str, n: int, config: dict, seed: int) -> dict:
    t = a_described_triple(n, config, seed)
    preds = config["predicates"]
    k = (n // preds) // 2
    subjects = " ".join(f"<{EX}e/{j}>" for j in range(k, k + 50))
    q = {
        # A few rows whatever the size.
        "id_var_pred": "SELECT ?s ?p ?o WHERE { " + statement(encoding, t["stmt"], "?s", "?p", "?o") + " }",
        "id_const_pred": "SELECT ?s ?o WHERE { " + statement(encoding, t["stmt"], "?s", t["predicate"], "?o") + " }",
        "subject_var_pred": "SELECT ?r ?p WHERE { " + statement(encoding, "?r", t["subject"], "?p", "?o") + " }",
        "subject_const_pred": "SELECT ?r WHERE { " + statement(encoding, "?r", t["subject"], t["predicate"], "?o") + " }",
        "values_50_subjects": f"SELECT ?s ?p ?o WHERE {{ VALUES ?s {{ {subjects} }} "
        + statement(encoding, "?r", "?s", "?p", "?o") + " }",
        # Answers that grow with the store.
        "join_asserted": "SELECT (COUNT(*) AS ?c) WHERE { ?s ex:p0 ?o . " + statement(encoding, "?r", "?s", "ex:p0", "?o") + " }",
        "all_statements": "SELECT ?s ?p ?o WHERE { " + statement(encoding, "?r", "?s", "?p", "?o") + " }",
    }  # fmt: skip
    if encoding == "rdf12":
        q["all_triple_terms"] = "SELECT ?t WHERE { ?r rdf:reifies ?t }"
    return q


def new_statements(encoding: str, start: int, predicate: str) -> str:
    """INSERT_SIZE new described triples, as N-Triples."""
    lines = []
    for i in range(start, start + INSERT_SIZE):
        s, o, r = f"<{EX}new/{i}>", f"<{EX}e/{i % 1000}>", f"<{EX}newstmt/{i}>"
        lines.append(f"{s} {predicate} {o} .")
        if encoding == "reification":
            lines += [
                f"{r} <{RDF}type> <{RDF}Statement> .",
                f"{r} <{RDF}subject> {s} .",
                f"{r} <{RDF}predicate> {predicate} .",
                f"{r} <{RDF}object> {o} .",
            ]
        else:
            lines.append(f"{r} <{RDF}reifies> <<( {s} {predicate} {o} )>> .")
        lines.append(f"{r} <{EX}source> <{EX}src/{i % 1000}> .")
    return "\n".join(lines) + "\n"


def delete_updates(encoding: str) -> list:
    statements = (
        ["DELETE WHERE { ?r rdf:reifies ?t }"]
        if encoding == "rdf12"
        else [
            "DELETE WHERE { ?r rdf:type rdf:Statement }",
            "DELETE WHERE { ?r rdf:subject ?x }",
            "DELETE WHERE { ?r rdf:predicate ?x }",
            "DELETE WHERE { ?r rdf:object ?x }",
        ]
    )
    return statements + ["DELETE WHERE { ?r ex:source ?x }", "DELETE WHERE { ?r ex:since ?x }"]


# ---------------------------------------------------------------------------------------------
# Measurement (child process)
# ---------------------------------------------------------------------------------------------


def timed(f) -> float:
    t = time.perf_counter()
    f()
    return time.perf_counter() - t


def measure(path: Path, encoding: str, n: int, config: dict, seed: int, repeats: int, batch_size: int) -> dict:
    import maplib

    out = {}
    m = maplib.Model()
    try:
        out["load_s"] = timed(lambda: m.read(str(path), format="ntriples", triples_batch_size=batch_size))
    except Exception as e:  # noqa: BLE001 - recorded, so other runs go on
        return {"error": f"load: {type(e).__name__}: {str(e)[:300]}"}
    out["maplib_mb"] = maplib.memory_usage() / 1e6
    out["peak_rss_mb_load"] = base.peak_rss_mb()
    out["stored_triples"] = base.result_rows(m.query("SELECT (COUNT(*) AS ?c) WHERE { ?s ?p ?o }"))

    qs = {}
    for name, q in queries(encoding, n, config, seed).items():
        try:
            res = m.query(PREFIXES + q)
            times = [timed(lambda: m.query(PREFIXES + q, cache=False)) for _ in range(repeats)]
            qs[name] = {"rows": base.result_rows(res), "median_s": statistics.median(times)}
        except Exception as e:  # noqa: BLE001
            qs[name] = {"error": f"{type(e).__name__}: {str(e)[:300]}"}
    out["queries"] = qs

    # Inserts: new statements about ex:p0, about a predicate without statements, and plain
    # triples of ex:p0. Each round adds new subjects, so every statement is new.
    start = 10 * n
    for name, make in [
        ("insert_same_predicate_ms", lambda i: new_statements(encoding, i, f"<{EX}p0>")),
        ("insert_new_predicate_ms", lambda i: new_statements(encoding, i, f"<{EX}fresh>")),
        ("insert_plain_ms", lambda i: "".join(
            f"<{EX}plain/{j}> <{EX}p0> <{EX}e/{j % 1000}> .\n" for j in range(i, i + INSERT_SIZE))),
    ]:  # fmt: skip
        times = []
        for _ in range(INSERT_ROUNDS):
            doc = make(start)
            start += INSERT_SIZE
            times.append(timed(lambda: m.reads(doc, format="ntriples")))
        out[name] = statistics.median(times) * 1000

    # Deleting every statement, last, as it changes the store.
    try:
        out["delete_s"] = timed(lambda: [m.update(PREFIXES + u) for u in delete_updates(encoding)])
        m.compact()
        out["maplib_mb_after_delete"] = maplib.memory_usage() / 1e6
        out["stored_triples_after_delete"] = base.result_rows(
            m.query("SELECT (COUNT(*) AS ?c) WHERE { ?s ?p ?o }"))  # fmt: skip
    except Exception as e:  # noqa: BLE001
        out["delete_error"] = f"{type(e).__name__}: {str(e)[:300]}"
    out["peak_rss_mb"] = base.peak_rss_mb()
    return out


def child(args):
    config = json.loads(args.config)
    res = measure(Path(args.path), args.encoding, args.triples, config, args.seed, args.repeats, args.batch_size)
    print("RESULT " + json.dumps(res), flush=True)


def run_child(path: Path, encoding: str, n: int, config: dict, seed: int, repeats: int, batch_size: int) -> dict:
    cmd = [
        sys.executable, __file__, "child", "--path", str(path), "--encoding", encoding,
        "--triples", str(n), "--config", json.dumps(config), "--seed", str(seed),
        "--repeats", str(repeats), "--batch-size", str(batch_size),
    ]  # fmt: skip
    env = dict(os.environ)
    env["POLARS_OOC_DRIFT_THRESHOLD"] = str(64 * 1024)  # see rdf12_benchmark.run_child
    p = subprocess.run(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True, env=env)
    for line in p.stdout.splitlines():
        if line.startswith("RESULT "):
            return json.loads(line[len("RESULT "):])
    return {"error": f"child exited with {p.returncode}: {p.stderr[-1000:]}"}


# ---------------------------------------------------------------------------------------------
# Orchestration and reporting
# ---------------------------------------------------------------------------------------------


def metrics_of(r: dict) -> dict:
    out = {}
    for k in ("load_s", "maplib_mb", "peak_rss_mb", "insert_same_predicate_ms", "insert_new_predicate_ms",
              "insert_plain_ms", "delete_s", "maplib_mb_after_delete"):  # fmt: skip
        if isinstance(r.get(k), (int, float)):
            out[k] = r[k]
    for name, q in r.get("queries", {}).items():
        if "median_s" in q:
            out[f"q:{name}"] = q["median_s"] * 1000
    return out


def slope(points: list) -> float | None:
    """The least squares slope of log(value) against log(size)."""
    pts = [(math.log(n), math.log(v)) for n, v in points if v and v > 0]
    if len(pts) < 2:
        return None
    mx = sum(x for x, _ in pts) / len(pts)
    my = sum(y for _, y in pts) / len(pts)
    sxx = sum((x - mx) ** 2 for x, _ in pts)
    return sum((x - mx) * (y - my) for x, y in pts) / sxx if sxx else None


def slopes(results: dict) -> dict:
    series = {}
    for r in results["runs"]:
        if "error" in r:
            continue
        for k, v in metrics_of(r).items():
            series.setdefault((r["config"], r["encoding"], k), []).append((r["triples"], v))
    return {f"{c}|{e}|{k}": slope(pts) for (c, e, k), pts in series.items()}


def report(results: dict):
    by = {}
    for r in results["runs"]:
        by.setdefault((r["config"], r["encoding"]), []).append(r)
    sl = results["slopes"]
    for (config, enc), runs in sorted(by.items()):
        runs.sort(key=lambda r: r["triples"])
        print(f"\n== {config}, {enc}")
        errors = [f"{r['triples']:,}: {r['error'][:120]}" for r in runs if "error" in r]
        for e in errors:
            print("  ERROR " + e)
        ok = [r for r in runs if "error" not in r]
        if not ok:
            continue
        names = []
        for r in ok:
            for k in metrics_of(r):
                if k not in names:
                    names.append(k)
        print(f"{'metric':<28}" + "".join(f"{r['triples']:>12,}" for r in ok) + f"{'slope':>8}  expected")
        for k in names:
            row = f"{k:<28}"
            for r in ok:
                v = metrics_of(r).get(k)
                row += f"{v:>12.4g}" if v is not None else f"{'':>12}"
            s = sl.get(f"{config}|{enc}|{k}")
            exp = EXPECTED.get(k)
            row += f"{s:>8.2f}" if s is not None else f"{'':>8}"
            if exp:
                flag = "  GROWS" if s is not None and s > exp[0] + 0.3 else ""
                row += f"  {exp[0]}  {exp[1]}{flag}"
            print(row)
        for r in ok:
            if "delete_error" in r:
                print(f"  delete at {r['triples']:,}: {r['delete_error'][:150]}")
    check_agreement(results)


def check_agreement(results: dict):
    rows = {}
    for r in results["runs"]:
        for name, q in r.get("queries", {}).items():
            if "rows" in q:
                rows.setdefault((r["config"], r["triples"], name), {})[r["encoding"]] = q["rows"]
    for (c, n, name), per in sorted(rows.items()):
        if len(set(per.values())) > 1:
            print(f"WARNING: encodings disagree on {name} ({c}, {n:,} triples): {per}")


def run(args):
    busy = base.builds_running()
    if busy:
        sys.exit("Builds are running, which disturbs the timings:\n" + "\n".join(busy))
    import maplib

    build = base.build_info()
    base.check_build(build, args.allow_stale)
    sizes = [base.parse_count(x) for x in args.triples.split(",")]
    results = {
        "label": args.label,
        "git": base.git_info(),
        "build": build,
        "maplib_version": getattr(maplib, "__version__", None),
        "machine": {"platform": base.platform.platform(), "cpu_count": os.cpu_count()},
        "params": {"seed": args.seed, "repeats": args.repeats, "batch_size": args.batch_size,
                   "configs": {c: CONFIGS[c] for c in args.configs.split(",")}},  # fmt: skip
        "runs": [],
    }
    for config_name in args.configs.split(","):
        config = CONFIGS[config_name]
        for n in sizes:
            for enc in args.encodings.split(","):
                path = base.ensure_data(
                    Path(args.data_dir), n, enc, config["predicates"], config["reified"], args.seed,
                    config["described_predicates"],
                )  # fmt: skip
                print(f"{config_name:<8} {n:>12,} {enc:<12} ", end="", flush=True)
                res = run_child(path, enc, n, config, args.seed, args.repeats, args.batch_size)
                res.update({"config": config_name, "triples": n, "encoding": enc})
                results["runs"].append(res)
                if "error" in res:
                    print("ERROR " + res["error"].splitlines()[0][:150], flush=True)
                else:
                    print(f"load {res['load_s']:7.2f}s  maplib {res['maplib_mb']:9.1f} MB  "
                          f"peak {res['peak_rss_mb']:9.1f} MB", flush=True)  # fmt: skip
    results["slopes"] = slopes(results)
    report(results)
    out = Path(args.out) if args.out else base.DEFAULT_RESULTS / f"scaling-{args.label}.json"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(json.dumps(results, indent=2))
    print(f"\nresults written to {out}")


def compare(args):
    files = [json.loads(Path(f).read_text()) for f in args.files]
    labels = [f["label"] + "@" + f["git"]["commit"] for f in files]
    keys = sorted({k for f in files for k in f["slopes"]})
    print(f"{'graph|encoding|metric':<52}" + "".join(f"{lbl[:20]:>22}" for lbl in labels) + "  expected")
    for k in keys:
        metric = k.split("|")[2]
        row = f"{k:<52}"
        for f in files:
            s = f["slopes"].get(k)
            row += f"{s:>22.2f}" if s is not None else f"{'':>22}"
        exp = EXPECTED.get(metric)
        print(row + (f"  {exp[0]}" if exp else ""))


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)

    p = sub.add_parser("run", help="generate data as needed and measure")
    p.add_argument("--triples", default="1e6,1e7", help="comma separated sizes, e.g. 1e6,1e7,3e7")
    p.add_argument("--configs", default=",".join(CONFIGS))
    p.add_argument("--encodings", default=",".join(ENCODINGS))
    p.add_argument("--repeats", type=int, default=5)
    p.add_argument("--batch-size", type=base.parse_count, default=BATCH_SIZE)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--label", default="run")
    p.add_argument("--out", default=None)
    p.add_argument("--data-dir", default=str(base.DEFAULT_DATA))
    p.add_argument("--allow-stale", action="store_true")
    p.set_defaults(func=run)

    p = sub.add_parser("compare", help="compare the slopes of result files")
    p.add_argument("files", nargs="+")
    p.set_defaults(func=compare)

    p = sub.add_parser("child")
    p.add_argument("--path", required=True)
    p.add_argument("--encoding", required=True)
    p.add_argument("--triples", type=int, required=True)
    p.add_argument("--config", required=True)
    p.add_argument("--seed", type=int, required=True)
    p.add_argument("--repeats", type=int, required=True)
    p.add_argument("--batch-size", type=int, required=True)
    p.set_defaults(func=child)

    args = ap.parse_args()
    args.func(args)


if __name__ == "__main__":
    main()
